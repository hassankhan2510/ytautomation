"""
SPECULATIVE IMAGINATION — can the cloud imagine new regions BEFORE the user gets there, so a phone
never waits for generation?

At every frame t the predictor extrapolates the user's motion L frames ahead (constant velocity and
turn rate), renders that predicted view from the shared state with a widened field of view (margin
for prediction error), and pre-generates whatever is novel there. When frame t+L actually arrives,
anything still missing must be generated ON DEMAND (= the user waits). We measure, versus lookahead L:
  ready   : share of the novel pixels the user meets that were already imagined in advance
  waste   : pre-generated pixels the user never ends up looking at, relative to pixels used
Exact depth is used for lifting (this isolates prediction/scheduling, not lifting quality).
"""
import math
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "shotc"))
import multiuser as MU  # noqa: E402
import ww  # noqa: E402


def predict(cam, f, L, widen):
    """Constant velocity + constant yaw-rate extrapolation of the camera, field of view widened."""
    p0, p1 = cam[max(f - 1, 0), 0:3], cam[f, 0:3]
    f0, f1 = cam[max(f - 1, 0), 3:6], cam[f, 3:6]
    yaw0, yaw1 = math.atan2(f0[0], -f0[2]), math.atan2(f1[0], -f1[2])
    dyaw = (yaw1 - yaw0 + math.pi) % (2 * math.pi) - math.pi
    pos = p1 + L * (p1 - p0)
    a = yaw1 + L * dyaw
    fwd = np.array([math.sin(a), f1[1], -math.cos(a)])
    fwd /= np.linalg.norm(fwd)
    right = np.cross(fwd, [0.0, 1.0, 0.0])
    right /= np.linalg.norm(right)
    up = np.cross(right, fwd)
    th = math.tan(math.atan(cam[f, 12]) * widen)
    return np.array([*pos, *fwd, *right, *up, th])


def run(L, F=200, W=128, H=128, seed=0, widen=1.35, n=7):
    SPH, BOX, MAT, LGT, block, street = MU.city(n=n)
    cam = MU.walkers(1, F, block, street, n=n, seed=seed)[0]
    P = np.zeros((0, 3)); C = np.zeros((0, 3), np.float32); R = np.zeros(0)
    origin = np.zeros(0, np.int64)   # 1 = pre-generated by speculation, 0 = generated on demand
    used = np.zeros(0, bool)         # has this point ever been seen by the real user?
    on_demand = spec_px = 0

    def lift(Cm, idx, rgb, z, hole, tag):
        nonlocal P, C, R, origin, used
        Pn, Rn, yn, xn = ww.unproject(Cm, idx, W, H, np.where(np.isfinite(z), z, 1.0), hole)
        P = np.vstack([P, Pn]); R = np.concatenate([R, Rn]); C = np.vstack([C, rgb[yn, xn]])
        origin = np.concatenate([origin, np.full(len(Pn), tag)]); used = np.concatenate([used, np.full(len(Pn), tag == 0)])
        return len(Pn)

    for f in range(F):
        # 1) the REAL view: what is still missing must be generated now (user waits)
        rgb, z = ww.gt_frame(cam, f, W, H, SPH, BOX, MAT, LGT)
        sky = ~np.isfinite(z)
        if len(P):
            _, _, cov, _, Im = ww.splat(P, C, R.astype(np.float64), cam, f, W, H, np.ones(len(P)))
            used[Im[Im >= 0]] = True
        else:
            cov = np.zeros((H, W), bool)
        hole = ~cov & ~sky
        if hole.any():
            on_demand += lift(cam, f, rgb, z, hole, 0)
        # 2) SPECULATE: imagine the predicted view L frames ahead (in the background)
        if L > 0:
            pc = predict(cam, f, L, widen)[None]
            prgb, pz = ww.gt_frame(pc, 0, W, H, SPH, BOX, MAT, LGT)
            _, _, pcov, _, _ = ww.splat(P, C, R.astype(np.float64), pc, 0, W, H, np.ones(len(P)))
            ph = ~pcov & np.isfinite(pz)
            if ph.mean() > 0.002:
                spec_px += lift(pc, 0, prgb, pz, ph, 1)
    spec_used = int((used & (origin == 1)).sum())
    met = on_demand + spec_used  # novel content the user actually met
    return {"L": L, "ready_pct": 100 * spec_used / max(met, 1), "on_demand_px_per_frame": on_demand / F,
            "waste_ratio": (spec_px - spec_used) / max(met, 1), "total_generated_vs_no_spec": (on_demand + spec_px) / max(met, 1)}


if __name__ == "__main__":
    print("lookahead at 24 fps | world ready before the user arrives | still generated while user waits | wasted imagination | total generation vs no speculation")
    for L in (0, 3, 6, 12, 24):
        rs = [run(L, seed=s) for s in (0, 1)]
        r = {k: float(np.mean([x[k] for x in rs])) for k in rs[0]}
        print(f"  {L:2d} frames ({L / 24:4.2f}s) | {r['ready_pct']:5.1f}% | {r['on_demand_px_per_frame']:7.1f} px/frame | {r['waste_ratio']:5.2f}x of used | {r['total_generated_vs_no_spec']:4.2f}x", flush=True)
