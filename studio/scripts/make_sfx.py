"""
Synthesize the studio's sound-effect kit from scratch (pure numpy, no samples) -> public/sfx/*.wav

  python scripts/make_sfx.py

Everything is generated by code, so there is no licence to track and nothing to credit.
Sounds are short, band-limited and mixed low so they sit UNDER a voice, not over it.
"""
import os
import wave

import numpy as np

SR = 44100
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "public", "sfx")
rng = np.random.default_rng(7)


def t(d):
    return np.arange(int(SR * d)) / SR


def env(n, attack, release, curve=2.0):
    """Attack/release envelope (fractions of length), curved for a natural swell/decay."""
    e = np.ones(n)
    a, r = max(1, int(n * attack)), max(1, int(n * release))
    e[:a] = np.linspace(0, 1, a) ** curve
    e[-r:] *= np.linspace(1, 0, r) ** curve
    return e


def sweep_bandpass(x, f0, f1, q=1.2):
    """Time-varying biquad band-pass (frequency glides f0->f1 exponentially) — the whoosh core."""
    n = len(x)
    freqs = f0 * (f1 / f0) ** (np.arange(n) / max(1, n - 1))
    y = np.zeros(n)
    x1 = x2 = y1 = y2 = 0.0
    for i in range(n):
        w0 = 2 * np.pi * freqs[i] / SR
        alpha = np.sin(w0) / (2 * q)
        b0, b2, a0 = alpha, -alpha, 1 + alpha
        a1, a2 = -2 * np.cos(w0), 1 - alpha
        yi = (b0 * x[i] + b2 * x2 - a1 * y1 - a2 * y2) / a0
        x2, x1, y2, y1 = x1, x[i], y1, yi
        y[i] = yi
    return y


def lowpass(x, fc):
    a = np.exp(-2 * np.pi * fc / SR)
    y = np.zeros_like(x)
    acc = 0.0
    for i, v in enumerate(x):
        acc = (1 - a) * v + a * acc
        y[i] = acc
    return y


def norm(x, peak=0.8):
    m = np.max(np.abs(x)) or 1.0
    return x / m * peak


def save(name, x, peak=0.8):
    x = norm(x, peak)
    fade = min(len(x), int(0.004 * SR))
    x[:fade] *= np.linspace(0, 1, fade)
    x[-fade:] *= np.linspace(1, 0, fade)
    os.makedirs(OUT, exist_ok=True)
    with wave.open(os.path.join(OUT, name + ".wav"), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes((x * 32767).astype(np.int16).tobytes())
    print(f"{name:12s} {len(x) / SR:4.2f}s")


def pink(n):
    w = rng.standard_normal(n)
    f = np.fft.rfft(w)
    f /= np.maximum(1, np.sqrt(np.arange(len(f))))
    return np.fft.irfft(f, n)


# WHOOSH — air rushing past: pink noise through a band-pass gliding up then down, swell + tail.
n = int(SR * 0.62)
up = sweep_bandpass(pink(n), 500, 3800, q=2.2)
up = up - lowpass(up, 260)  # cut the low rumble so it reads as air, not wind noise
save("whoosh", up * env(n, 0.55, 0.45, 1.6), 0.75)

# SWOOSH — quicker, brighter, for normal cuts.
n = int(SR * 0.32)
save("swoosh", sweep_bandpass(pink(n), 900, 4200, q=1.1) * env(n, 0.45, 0.55, 1.4), 0.7)

# IMPACT — cinematic hit: sub-bass sine dropping 65->38 Hz with exponential decay + dull transient.
d = 1.1
tt = t(d)
freq = 38 + 27 * np.exp(-tt * 9)
sub = np.sin(2 * np.pi * np.cumsum(freq) / SR) * np.exp(-tt * 3.6)
click = lowpass(rng.standard_normal(len(tt)), 1800) * np.exp(-tt * 45) * 0.9
body = np.tanh((sub * 1.6 + click) * 1.4)
save("impact", body, 0.85)

# RISER — tension build: noise band-pass sweeping up + rising sine, crescendo, hard stop.
d = 1.3
n = int(SR * d)
tt = t(d)
nz = sweep_bandpass(pink(n), 250, 6500, q=1.4)
tone = np.sin(2 * np.pi * np.cumsum(180 * (7.0 ** (tt / d))) / SR) * 0.35
save("riser", (nz + tone) * (tt / d) ** 2.2, 0.7)

# POP — emphasis word: short sine with a fast pitch drop.
d = 0.09
tt = t(d)
f = 950 * np.exp(-tt * 14) + 420
save("pop", np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-tt * 38), 0.6)

# CLICK — UI tick.
d = 0.035
tt = t(d)
save("click", (np.sin(2 * np.pi * 2400 * tt) * 0.6 + rng.standard_normal(len(tt)) * 0.4) * np.exp(-tt * 160), 0.55)

# TYPE — typewriter/keyboard key: filtered noise snap + low knock.
d = 0.05
tt = t(d)
save("type", lowpass(rng.standard_normal(len(tt)), 4500) * np.exp(-tt * 120) + np.sin(2 * np.pi * 180 * tt) * np.exp(-tt * 90) * 0.5, 0.5)

# GLITCH — digital stutter: gated bit-crushed noise + square blips.
d = 0.38
n = int(SR * d)
tt = t(d)
gate = (np.floor(tt * 42) % 3 != 1).astype(float)
crushed = np.round(rng.standard_normal(n) * 3) / 3
blip = np.sign(np.sin(2 * np.pi * (300 + 900 * (np.floor(tt * 21) % 4)) * tt)) * 0.35
save("glitch", (lowpass(crushed, 5000) * 0.6 + blip) * gate * env(n, 0.05, 0.3, 1.0), 0.55)

# DING — soft bell for the end card / notifications: two inharmonic partials, long decay.
d = 1.2
tt = t(d)
bell = sum(a * np.sin(2 * np.pi * f * tt) * np.exp(-tt * k) for f, a, k in [(1318.5, 1.0, 3.2), (1977, 0.5, 4.5), (2637, 0.25, 6.0), (659.3, 0.3, 2.5)])
save("ding", bell, 0.55)
